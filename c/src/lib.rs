//! The C interface of grobx: the library `libgrobxc.so`, whose functions
//! `grobx.h` declares. `grobx_groebner` takes what `grobx.groebner` takes,
//! calls the crate's `groebner`, and hands back what the Python result
//! carries but its digest and its seed, which `params.seed` holds
//! (`OBJECTIVES.md`, _Language and build_).
//!
//! The types and constants carry the header's names, so that the test code
//! and a reader match them by name.

use std::any::Any;
use std::ffi::{CStr, CString, c_char, c_int};
use std::num::{NonZeroU32, NonZeroUsize};
use std::panic::{self, AssertUnwindSafe};
use std::ptr;
use std::slice;
use std::time::Duration;

use grobx::{CheckerMode, Error, MonomialOrder, Outcome, Params, Stop, Threads};

// small-block-time.4 design -- the C library sets the crate's allocator as its global allocator, not the crate setting it for every program that links it (not measured)
#[global_allocator]
static GLOBAL: grobx::Allocator = grobx::Allocator;

// c-interface.14 design -- the header is written by hand and a test compares its sizes, offsets, and constants with the library's, not generated by cbindgen, which the cargo cache lacks (not measured)
/// The call returned a result.
pub const GROBX_OK: c_int = 0;
/// `Error::Syntax`.
pub const GROBX_SYNTAX: c_int = 1;
/// `Error::UnknownVariable`.
pub const GROBX_UNKNOWN_VARIABLE: c_int = 2;
/// `Error::RepeatedVariable`.
pub const GROBX_REPEATED_VARIABLE: c_int = 3;
/// `Error::Characteristic`.
pub const GROBX_CHARACTERISTIC: c_int = 4;
/// `Error::Overflow`.
pub const GROBX_OVERFLOW: c_int = 5;
/// `Error::NoInverse`.
pub const GROBX_NO_INVERSE: c_int = 6;
/// `Error::Order`.
pub const GROBX_ORDER: c_int = 7;
/// `Error::Memory`.
pub const GROBX_MEMORY: c_int = 8;
/// Any other error of the crate, `Error::Misfit` and `Error::Malloc` among
/// them.
pub const GROBX_ERROR: c_int = 9;
/// An argument the interface refuses before the call.
pub const GROBX_ARGUMENT: c_int = 10;
/// The call panicked.
pub const GROBX_PANIC: c_int = 11;
/// `Error::Size`.
pub const GROBX_SIZE: c_int = 12;
/// `Error::Drops`.
pub const GROBX_DROPS: c_int = 13;

/// `grobx_params.deadline` and `grobx_params.memory`: no bound.
pub const GROBX_NONE: u64 = u64::MAX;

/// `grobx_params.order`: `MonomialOrder::Grevlex`.
pub const GROBX_GREVLEX: u32 = 0;
/// `grobx_params.order`: `MonomialOrder::Lex`.
pub const GROBX_LEX: u32 = 1;
/// `grobx_params.order`: `MonomialOrder::Block` of `grobx_params.blocks`.
pub const GROBX_BLOCK: u32 = 2;

// c-interface.3 design -- the checker is a mode and the cheap mode's points, two fields, not one integer with a value set aside for the exact mode (not measured)
/// `grobx_params.checker`: no checker.
pub const GROBX_CHECKER_OFF: u32 = 0;
/// `grobx_params.checker`: `CheckerMode::Exact`.
pub const GROBX_CHECKER_EXACT: u32 = 1;
/// `grobx_params.checker`: `CheckerMode::Cheap` at `grobx_params.points`.
pub const GROBX_CHECKER_CHEAP: u32 = 2;

/// `grobx_result.stopped`: no bound stopped the call.
pub const GROBX_STOP_NONE: c_int = 0;
/// `grobx_result.stopped`: `Stop::Deadline`.
pub const GROBX_STOP_DEADLINE: c_int = 1;
/// `grobx_result.stopped`: `Stop::Cancel`.
pub const GROBX_STOP_CANCEL: c_int = 2;
/// `grobx_result.stopped`: `Stop::Memory`.
pub const GROBX_STOP_MEMORY: c_int = 3;

/// `grobx_result.certified`: the checker did not rule: the call did not ask
/// for it, a bound stopped the call, or the call failed.
pub const GROBX_UNCHECKED: c_int = -1;
/// `grobx_result.certified`: the checker rejected the result.
pub const GROBX_REJECTED: c_int = 0;
/// `grobx_result.certified`: the checker certified the result.
pub const GROBX_CERTIFIED: c_int = 1;

// c-interface.11 practice: opaque handle -- the cancel flag is a handle the library allocates and frees, not a C11 atomic_bool of the caller's that the call reads
/// A flag another thread raises to stop a call: the crate's `Cancel`,
/// which the call clones.
#[allow(non_camel_case_types, reason = "the C name that grobx.h declares")]
pub struct grobx_cancel(grobx::Cancel);

// c-interface.1 design -- the parameters are a struct the header declares, which grobx_params_new fills and whose other fields the caller sets by name, not an opaque handle with a setter per parameter or one function with every parameter as an argument (not measured)
/// The parameters of a call, as `grobx.h` declares them.
#[allow(non_camel_case_types, reason = "the C name that grobx.h declares")]
#[repr(C)]
#[derive(Clone, Copy, Debug)]
pub struct grobx_params {
    /// `GROBX_GREVLEX`, `GROBX_LEX`, or `GROBX_BLOCK`.
    pub order: u32,
    /// `GROBX_BLOCK`: the block sizes, `nblocks` of them.
    pub blocks: *const usize,
    pub nblocks: usize,
    /// 0: all the machine has.
    pub threads: usize,
    pub seed: u64,
    /// Milliseconds, the whole call; `GROBX_NONE`: none.
    pub deadline: u64,
    /// NULL: none.
    pub cancel: *mut grobx_cancel,
    /// Bytes of resident set; `GROBX_NONE`: none.
    pub memory: u64,
    /// `GROBX_CHECKER_OFF`, `_EXACT`, or `_CHEAP`.
    pub checker: u32,
    /// The cheap mode's points, at least 1.
    pub points: u32,
    pub cofactors: bool,
    // call-report.17 design -- bool report is appended to grobx_params and char *report to grobx_result, freed by grobx_result_free, not a function of its own that returns the report nor a callback per line (not measured)
    /// Whether the result holds the call report.
    pub report: bool,
}

// c-interface.5 design -- the result is a struct the caller provides, which the call fills and grobx_result_free frees, not a pointer to a result the library allocates or an opaque result read by a function per field (not measured)
/// What a call returns, as `grobx.h` declares it. Every text is
/// NUL-terminated and the library's, NULL where there is none.
#[allow(non_camel_case_types, reason = "the C name that grobx.h declares")]
#[repr(C)]
#[derive(Debug)]
pub struct grobx_result {
    /// The basis text; NULL where a bound stopped the call or the status
    /// is not `GROBX_OK`.
    pub basis: *mut c_char,
    /// The cofactor text, where asked for and computed.
    pub cofactors: *mut c_char,
    /// `GROBX_STOP_NONE`, or the bound that stopped the call.
    pub stopped: c_int,
    /// `GROBX_UNCHECKED`, `GROBX_REJECTED`, or `GROBX_CERTIFIED`.
    pub certified: c_int,
    /// Why the checker rejected the result.
    pub flaw: *mut c_char,
    /// The error's message where the status is not `GROBX_OK`.
    pub error: *mut c_char,
    /// The call report, where asked for and the status is `GROBX_OK`.
    pub report: *mut c_char,
}

/// The parameters with the order, threads, and seed given, no blocks, every
/// bound absent, no checker, no cofactors, and no report. `order` is read by
/// `grobx_groebner`, not here.
#[unsafe(no_mangle)]
pub extern "C" fn grobx_params_new(order: u32, threads: usize, seed: u64) -> grobx_params {
    grobx_params {
        order,
        blocks: ptr::null(),
        nblocks: 0,
        threads,
        seed,
        deadline: GROBX_NONE,
        cancel: ptr::null_mut(),
        memory: GROBX_NONE,
        checker: GROBX_CHECKER_OFF,
        points: 0,
        cofactors: false,
        report: false,
    }
}

/// `grobx_params_new` with grevlex, all the machine's threads, and a seed
/// from `grobx::random_seed`, which `seed` holds for a replay: the C form of
/// `Params::default`.
#[unsafe(no_mangle)]
pub extern "C" fn grobx_params_default() -> grobx_params {
    grobx_params_new(GROBX_GREVLEX, 0, grobx::random_seed())
}

/// The reduced Gröbner basis of the instance `text` under `params`, written
/// to `*result`, and the status: `GROBX_OK`, or the error's, whose message
/// `result.error` holds. A NULL `result` is `GROBX_ARGUMENT`, and nothing
/// is written.
///
/// # Safety
///
/// `text` is NULL or a NUL-terminated text. `params` is NULL or points to
/// a `grobx_params` whose `blocks` is NULL or points to `nblocks` sizes and whose
/// `cancel` is NULL or a flag of `grobx_cancel_new` not yet freed. `result`
/// is NULL or points to storage for a `grobx_result`, whose old contents
/// are neither read nor freed.
#[unsafe(no_mangle)]
pub unsafe extern "C" fn grobx_groebner(
    text: *const c_char,
    params: *const grobx_params,
    result: *mut grobx_result,
) -> c_int {
    if result.is_null() {
        return GROBX_ARGUMENT;
    }
    // c-interface.10 practice: catch_unwind at the FFI boundary -- a panic in the call is caught and returned as GROBX_PANIC, not left to abort the process as a panic that leaves an extern "C" function does
    // c-interface.24 design -- a caught panic still reaches the process's panic hook, which prints it on standard error by default, not a hook of the library's that keeps it quiet (not measured)
    // SAFETY: `text` and `params` are as `call` takes them, this function's
    // condition.
    let (status, filled) =
        match panic::catch_unwind(AssertUnwindSafe(|| unsafe { call(text, params) })) {
            // c-interface.7 design -- GROBX_OK where the call returns a result, a call a bound stopped among them, not a status of its own for each bound (not measured)
            Ok(Ok(outcome)) => (GROBX_OK, outcome),
            Ok(Err((status, message))) => (status, failed(message)),
            Err(payload) => (GROBX_PANIC, failed(panicked(&*payload))),
        };
    // c-interface.17 design -- the call writes every field of the result whatever its status, not the fields left as they were where it fails (not measured)
    // SAFETY: `result` is not NULL and points to storage for a grobx_result,
    // this function's condition. `write` writes the struct whole and reads or
    // drops nothing it held.
    unsafe { result.write(filled) };
    status
}

/// The call: the arguments read into `Params`, the crate's `groebner`, and
/// its outcome as the C result; or the status and message of what the
/// interface or the crate refuses.
///
/// # Safety
///
/// As `grobx_groebner`'s `text` and `params`.
unsafe fn call(
    text: *const c_char,
    params: *const grobx_params,
) -> Result<grobx_result, (c_int, String)> {
    // SAFETY: `text` is NULL or a NUL-terminated text that outlives the call,
    // this function's condition.
    let text = unsafe { read(text, "text") }?;
    // SAFETY: `params` is NULL or points to a grobx_params.
    let Some(given) = (unsafe { params.as_ref() }) else {
        return Err(argument("params is NULL".to_string()));
    };
    // c-interface.4 design -- a field that holds one of a few values is an integer the library checks, not a Rust enum with repr(C), whose value outside its variants is undefined behaviour (not measured)
    let checker = match given.checker {
        GROBX_CHECKER_OFF => None,
        GROBX_CHECKER_EXACT => Some(CheckerMode::Exact),
        GROBX_CHECKER_CHEAP => {
            let points = NonZeroU32::new(given.points).ok_or_else(|| {
                argument("params->points 0: the cheap mode takes at least 1 point".to_string())
            })?;
            Some(CheckerMode::Cheap { points })
        }
        other => {
            return Err(argument(format!(
                "params->checker {other}: GROBX_CHECKER_OFF, GROBX_CHECKER_EXACT, or \
                 GROBX_CHECKER_CHEAP"
            )));
        }
    };
    let order = match given.order {
        GROBX_GREVLEX => MonomialOrder::Grevlex,
        GROBX_LEX => MonomialOrder::Lex,
        // SAFETY: `given.blocks` is NULL or points to `given.nblocks` sizes,
        // this function's condition.
        GROBX_BLOCK => MonomialOrder::Block(unsafe { blocks(given) }?),
        other => {
            return Err(argument(format!(
                "params->order {other}: GROBX_GREVLEX, GROBX_LEX, or GROBX_BLOCK"
            )));
        }
    };
    // c-interface.15 design -- threads 0 is all the machine has, as grobx.groebner's keyword takes it, not SIZE_MAX (not measured)
    let threads = match NonZeroUsize::new(given.threads) {
        None => Threads::All,
        Some(n) => Threads::Count(n),
    };
    // c-interface.19 design -- no field turns signatures off: the call runs with them on, as a Python call does, not a field for Params::signatures (not measured)
    // input-redundancy-time.10 design -- no keyword, switch, or field sets Params::echelon: the call runs with it on, as with signatures, not a keyword, a switch, and a field for it (not measured)
    let mut params = Params::new(order, threads, given.seed);
    // c-interface.2 design -- an absent deadline or memory ceiling is UINT64_MAX, not a flag beside each value or a pointer that is NULL for none (not measured)
    params.deadline = (given.deadline != GROBX_NONE).then(|| Duration::from_millis(given.deadline));
    params.memory = (given.memory != GROBX_NONE).then_some(given.memory);
    // SAFETY: `cancel` is NULL or a flag of grobx_cancel_new not yet freed.
    params.cancel = unsafe { given.cancel.as_ref() }.map(|c| c.0.clone());
    params.checker = checker;
    params.cofactors = given.cofactors;
    params.report = given.report;
    let outcome = grobx::groebner(text, &params).map_err(|e| refused(&e))?;
    Ok(handed_back(outcome))
}

/// The block sizes of `given`, or `GROBX_ARGUMENT` where `blocks` is NULL
/// and `nblocks` is not 0. The crate refuses sizes that do not fit the
/// instance, none among them, as `Error::Order`.
///
/// # Safety
///
/// `given.blocks` is NULL or points to `given.nblocks` sizes.
unsafe fn blocks(given: &grobx_params) -> Result<Vec<usize>, (c_int, String)> {
    if given.nblocks == 0 {
        return Ok(Vec::new());
    }
    if given.blocks.is_null() {
        return Err(argument(format!(
            "params->blocks is NULL and params->nblocks {nblocks}",
            nblocks = given.nblocks
        )));
    }
    // SAFETY: `blocks` points to `nblocks` sizes.
    Ok(unsafe { slice::from_raw_parts(given.blocks, given.nblocks) }.to_vec())
}

// c-interface.20 design -- a text that is not UTF-8 is GROBX_ARGUMENT, refused before the call, not GROBX_SYNTAX at its line (not measured)
/// The NUL-terminated text at `ptr`, or `GROBX_ARGUMENT` naming `what`
/// where it is NULL or not UTF-8.
///
/// # Safety
///
/// `ptr` is NULL or a NUL-terminated text that outlives the call.
unsafe fn read<'a>(ptr: *const c_char, what: &str) -> Result<&'a str, (c_int, String)> {
    if ptr.is_null() {
        return Err(argument(format!("{what} is NULL")));
    }
    // SAFETY: `ptr` is a NUL-terminated text.
    unsafe { CStr::from_ptr(ptr) }
        .to_str()
        .map_err(|e| argument(format!("{what} is not UTF-8: {e}")))
}

/// `GROBX_ARGUMENT` with `message`.
fn argument(message: String) -> (c_int, String) {
    (GROBX_ARGUMENT, message)
}

// c-interface.8 design -- one status per variant of the crate's Error a call reaches, GROBX_ERROR for any other, and GROBX_ARGUMENT for what the interface refuses, not one status for every error (not measured)
// c-interface.9 design -- the error's message, the Display of the crate's error or what the interface refused, is a field of the result, not a thread-local last error or an out-parameter of its own (not measured)
/// The status of the crate's error, and its message.
fn refused(e: &Error) -> (c_int, String) {
    let status = match e {
        Error::Syntax { .. } => GROBX_SYNTAX,
        Error::UnknownVariable { .. } => GROBX_UNKNOWN_VARIABLE,
        Error::RepeatedVariable { .. } => GROBX_REPEATED_VARIABLE,
        Error::Characteristic { .. } => GROBX_CHARACTERISTIC,
        Error::Overflow { .. } => GROBX_OVERFLOW,
        Error::Size => GROBX_SIZE,
        Error::NoInverse { .. } => GROBX_NO_INVERSE,
        Error::Order { .. } => GROBX_ORDER,
        Error::Memory => GROBX_MEMORY,
        Error::Drops { .. } => GROBX_DROPS,
        Error::Misfit { .. } | Error::Malloc { .. } | _ => GROBX_ERROR,
    };
    (status, e.to_string())
}

/// The message of a panic: its payload where that is a text.
fn panicked(payload: &(dyn Any + Send)) -> String {
    let said = payload
        .downcast_ref::<&str>()
        .copied()
        .or_else(|| payload.downcast_ref::<String>().map(String::as_str));
    match said {
        Some(said) => format!("the call panicked: {said}"),
        None => "the call panicked".to_string(),
    }
}

// c-interface.18 design -- certified is one int, -1 unchecked, 0 rejected, 1 certified, not two bool fields for whether the checker ruled and its verdict (not measured)
/// The outcome as the C result.
fn handed_back(outcome: Outcome) -> grobx_result {
    grobx_result {
        basis: outcome.basis.map_or(ptr::null_mut(), handed),
        cofactors: outcome.cofactors.map_or(ptr::null_mut(), handed),
        stopped: match outcome.stopped {
            None => GROBX_STOP_NONE,
            Some(Stop::Deadline) => GROBX_STOP_DEADLINE,
            Some(Stop::Cancel) => GROBX_STOP_CANCEL,
            Some(Stop::Memory) => GROBX_STOP_MEMORY,
        },
        certified: match outcome.certified {
            None => GROBX_UNCHECKED,
            Some(false) => GROBX_REJECTED,
            Some(true) => GROBX_CERTIFIED,
        },
        flaw: outcome.flaw.map_or(ptr::null_mut(), handed),
        error: ptr::null_mut(),
        report: outcome.report.map_or(ptr::null_mut(), handed),
    }
}

/// The C result of a call that returned no outcome: `message` and nothing
/// else.
fn failed(message: String) -> grobx_result {
    grobx_result {
        basis: ptr::null_mut(),
        cofactors: ptr::null_mut(),
        stopped: GROBX_STOP_NONE,
        certified: GROBX_UNCHECKED,
        flaw: ptr::null_mut(),
        error: handed(message),
        report: ptr::null_mut(),
    }
}

// c-interface.6 design -- the texts are NUL-terminated, in and out, not a pointer and a length (not measured)
// text-stop-latency.10 design -- the Python module's copy of each text into a Python string, and the C interface's handover of its texts, stay without a check, not a copy in chunks with a check between them (log 0057-1)
/// `text` as a NUL-terminated text the caller frees by `grobx_result_free`.
/// Every NUL byte in it is removed; the crate's texts hold none.
fn handed(text: String) -> *mut c_char {
    let mut bytes = text.into_bytes();
    loop {
        match CString::new(bytes) {
            Ok(text) => return text.into_raw(),
            Err(nul) => {
                bytes = nul.into_vec();
                bytes.retain(|&b| b != 0);
            }
        }
    }
}

/// Frees every text `result` holds and sets it NULL, so that a second call
/// frees nothing. A NULL `result` frees nothing.
///
/// # Safety
///
/// `result` is NULL or points to a `grobx_result` that `grobx_groebner`
/// wrote, whose texts are each the library's or NULL.
#[unsafe(no_mangle)]
pub unsafe extern "C" fn grobx_result_free(result: *mut grobx_result) {
    // c-interface.16 practice: free(NULL) as a no-op -- grobx_result_free sets each text it frees NULL, and grobx_result_free(NULL) and grobx_cancel_free(NULL) do nothing, not a second free or a NULL argument undefined
    // SAFETY: `result` is NULL or points to a grobx_result.
    let Some(result) = (unsafe { result.as_mut() }) else {
        return;
    };
    for text in [
        &mut result.basis,
        &mut result.cofactors,
        &mut result.flaw,
        &mut result.error,
        &mut result.report,
    ] {
        if !text.is_null() {
            // SAFETY: a text that is not NULL came from `handed`.
            drop(unsafe { CString::from_raw(*text) });
            *text = ptr::null_mut();
        }
    }
}

// c-interface.12 design -- the digest is a function of a text, not a field the call fills (not measured)
/// SHA-256 of the NUL-terminated `text`: 64 lowercase hex digits and a
/// NUL written to `digest`. `GROBX_OK`, or `GROBX_ARGUMENT` where an
/// argument is NULL or the text is not UTF-8.
///
/// # Safety
///
/// `text` is NULL or a NUL-terminated text. `digest` is NULL or points to
/// 65 writable bytes.
#[unsafe(no_mangle)]
pub unsafe extern "C" fn grobx_digest(text: *const c_char, digest: *mut c_char) -> c_int {
    if digest.is_null() {
        return GROBX_ARGUMENT;
    }
    // SAFETY: `text` is NULL or a NUL-terminated text, this function's
    // condition, and it outlives the call.
    let Ok(text) = (unsafe { read(text, "text") }) else {
        return GROBX_ARGUMENT;
    };
    let hex = grobx::digest(text);
    // SAFETY: `digest` points to 65 writable bytes, and `hex` holds 64.
    unsafe {
        ptr::copy_nonoverlapping(hex.as_ptr().cast::<c_char>(), digest, 64);
        digest.add(64).write(0);
    }
    GROBX_OK
}

/// A new flag, not raised, which `grobx_cancel_free` frees once no call
/// uses it and no thread raises it.
#[unsafe(no_mangle)]
pub extern "C" fn grobx_cancel_new() -> *mut grobx_cancel {
    Box::into_raw(Box::new(grobx_cancel(grobx::Cancel::new())))
}

/// Raises the flag. NULL does nothing.
///
/// # Safety
///
/// `cancel` is NULL or a flag of `grobx_cancel_new` not yet freed.
#[unsafe(no_mangle)]
pub unsafe extern "C" fn grobx_cancel_set(cancel: *mut grobx_cancel) {
    // SAFETY: `cancel` is NULL or a live flag.
    if let Some(cancel) = unsafe { cancel.as_ref() } {
        cancel.0.set();
    }
}

/// Whether the flag is raised; false for NULL.
///
/// # Safety
///
/// `cancel` is NULL or a flag of `grobx_cancel_new` not yet freed.
#[unsafe(no_mangle)]
pub unsafe extern "C" fn grobx_cancel_is_set(cancel: *const grobx_cancel) -> bool {
    // SAFETY: `cancel` is NULL or a live flag.
    unsafe { cancel.as_ref() }.is_some_and(|cancel| cancel.0.is_set())
}

/// Frees the flag. NULL frees nothing.
///
/// # Safety
///
/// `cancel` is NULL or a flag of `grobx_cancel_new` not yet freed, which no
/// call uses and no thread raises any more.
#[unsafe(no_mangle)]
pub unsafe extern "C" fn grobx_cancel_free(cancel: *mut grobx_cancel) {
    // c-interface.16 practice: free(NULL) as a no-op -- grobx_result_free sets each text it frees NULL, and grobx_result_free(NULL) and grobx_cancel_free(NULL) do nothing, not a second free or a NULL argument undefined
    if !cancel.is_null() {
        // SAFETY: `cancel` came from grobx_cancel_new's Box.
        drop(unsafe { Box::from_raw(cancel) });
    }
}

// c-interface.13 design -- the version is a function that returns a static text, not a macro of the header (not measured)
/// The crate version, `grobx::VERSION`, a static NUL-terminated text. A
/// version with a NUL byte fails the build.
#[unsafe(no_mangle)]
pub extern "C" fn grobx_version() -> *const c_char {
    const LEN: usize = grobx::VERSION.len();
    const BYTES: [u8; LEN + 1] = {
        let mut bytes = [0; LEN + 1];
        bytes
            .split_at_mut(LEN)
            .0
            .copy_from_slice(grobx::VERSION.as_bytes());
        bytes
    };
    const VERSION: &CStr = match CStr::from_bytes_with_nul(&BYTES) {
        Ok(version) => version,
        Err(_) => panic!("grobx::VERSION holds a NUL byte"),
    };
    VERSION.as_ptr()
}
